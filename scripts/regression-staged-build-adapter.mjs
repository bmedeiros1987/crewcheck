import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {prepareCiValidation, checkAndBuildCiValidation} from './ci/staged-build-adapter.mjs';
import {manifest, resolvePreparedGeneration} from './v139/staged-preparation-prototype.mjs';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'crewcheck-ci-adapter-'));
const raw = path.join(root, 'raw'), dependencies = path.join(root, 'dependencies');
fs.mkdirSync(raw); fs.mkdirSync(dependencies);
const write = (base, file, text) => {const target = path.join(base, file); fs.mkdirSync(path.dirname(target), {recursive: true}); fs.writeFileSync(target, text);};
const git = args => {const result = spawnSync('git', args, {cwd: raw, encoding: 'utf8'}); assert.equal(result.status, 0, result.stderr); return result.stdout.trim();};
// Observable stand-ins test command order/arguments; the real toolchain remains a separate CI gate.
const tool = `import fs from 'node:fs';fs.appendFileSync('commands.jsonl',JSON.stringify(process.argv.slice(2))+'\\n');`;
write(dependencies, 'typescript/bin/tsc', tool);
write(dependencies, 'vite/bin/vite.js', tool);
write(raw, 'scripts/p1-concierge-journey/compile.mjs', tool);
write(raw, 'scripts/ci/smoke-deny-network.mjs', '');
write(raw, 'scripts/ci/sync-canonical-manual.mjs', '');
write(raw, 'scripts/worker.mjs', "import fs from 'node:fs';if(fs.readFileSync('server.mjs','utf8')!=='RAW')throw Error('replayed');fs.writeFileSync('server.mjs','PREPARED');");
write(raw, 'server.mjs', 'RAW');
git(['init']); git(['add', '.']); git(['-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-m', 'raw']);
const commit = git(['rev-parse', 'HEAD']);
const options = {repository: raw, commit, inputRoot: raw, inputKind: 'raw', storage: path.join(root, 'store'), validationParent: root, dependencyRoot: dependencies, worker: ['scripts/worker.mjs']};
fs.mkdirSync(path.join(root, 'validations'));
options.validationParent = path.join(root, 'validations');
const before = manifest(raw), index = git(['status', '--porcelain']);
assert.throws(() => prepareCiValidation({...options, inputKind: undefined}), /CI_ATTESTED_RAW_REQUIRED/);
assert.throws(() => prepareCiValidation({...options, inputKind: 'prepared'}), /CI_ATTESTED_RAW_REQUIRED/);
write(raw, '.crewcheck-source-preparation.json', '{"version":2}');
assert.throws(() => prepareCiValidation(options), /CI_PREPARED_OR_LEGACY_INPUT_FORBIDDEN/);
fs.unlinkSync(path.join(raw, '.crewcheck-source-preparation.json'));
const first = prepareCiValidation(options), repeat = prepareCiValidation(options);
assert.equal(first.status, 'prepared'); assert.equal(repeat.status, 'hit');
assert.notEqual(first.validation, repeat.validation);
assert.equal(first.generation, resolvePreparedGeneration(options.storage));
assert(fs.statSync(first.validation).mode & 0o200);
checkAndBuildCiValidation(first);
assert.deepEqual(fs.readFileSync(path.join(first.validation, 'commands.jsonl'), 'utf8').trim().split('\n').map(JSON.parse), [['--noEmit'], [], ['build', '--configLoader', 'native']]);
assert(!fs.existsSync(path.join(first.generation, 'commands.jsonl')));
assert.throws(() => checkAndBuildCiValidation(repeat, {gates: [['scripts/v139/apply.mjs']]}), /CI_RECURSIVE_COMMAND_FORBIDDEN/);
assert.throws(() => checkAndBuildCiValidation(repeat, {gates: [['-e', 'process.exit(7)']]}), {code: 'CI_COMMAND_FAILED'});
assert(!fs.existsSync(path.join(repeat.validation, 'commands.jsonl')), 'failed gate stops build');
const timed = prepareCiValidation(options);
assert.throws(() => checkAndBuildCiValidation(timed, {timeout: 100, gates: [['-e', 'setInterval(()=>{},1000)']]}), {code: 'CI_COMMAND_FAILED'});
assert(!fs.existsSync(path.join(timed.validation, 'commands.jsonl')), 'timeout stops build');
const validationCount = fs.readdirSync(options.validationParent).length;
const failedStorage = path.join(root, 'failed-store');
assert.throws(() => prepareCiValidation({...options, storage: failedStorage, worker: ['-e', 'process.exit(8)']}), /STAGING_WORKER_FAILED|STAGING_GATE_FAILED/);
assert(!fs.existsSync(path.join(failedStorage, 'current.json')), 'failed preparation has no fallback');
const timeoutStorage = path.join(root, 'timeout-store');
assert.throws(() => prepareCiValidation({...options, storage: timeoutStorage, commandTimeout: 100, worker: ['-e', 'setInterval(()=>{},1000)']}), /STAGING_WORKER_FAILED|STAGING_GATE_FAILED/);
assert(fs.existsSync(path.join(timeoutStorage, 'writer.lock')), 'preparation timeout retains its lease');
assert(!fs.existsSync(path.join(timeoutStorage, 'current.json')));
assert.equal(fs.readdirSync(options.validationParent).length, validationCount, 'failed preparation creates no validation fallback');
fs.writeFileSync(path.join(options.storage, 'writer.lock'), JSON.stringify({pid: process.pid, token: 'pending'}));
assert.throws(() => prepareCiValidation(options), /WRITER_BUSY|WRITER_LOCKED/);
assert.deepEqual(manifest(raw), before); assert.equal(git(['status', '--porcelain']), index);
console.log(JSON.stringify({status: 'PASS', commit, rawUnchanged: true, exclusiveCopies: true, legacyRejected: true, failureTimeoutLeaseClosed: true, root}));
