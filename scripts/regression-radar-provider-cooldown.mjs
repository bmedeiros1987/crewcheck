import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source=fs.readFileSync('server.mjs','utf8'),ast=ts.createSourceFile('server.mjs',source,99,true,ts.ScriptKind.JS);
const extract=name=>{const f=ast.statements.find(n=>ts.isFunctionDeclaration(n)&&n.name?.text===name);assert(f,name);return f.getText(ast);};
let now=Date.parse('2026-11-04T13:00:00Z');
const radarHealth=new Map(),scope=vm.createContext({radarHealth,process:{env:{AIRLABS_API_KEY:'SYNTHETIC'}},Date:class extends Date{static now(){return now;}}});
vm.runInContext(['providerAvailable','markProvider','noteProviderError'].map(extract).join('\n'),scope);
const available=()=>scope.providerAvailable('airlabs',['AIRLABS_API_KEY']);
assert.equal(available(),true);
scope.markProvider('airlabs',true,200);now+=1000;scope.markProvider('airlabs',false,503);
assert.equal(available(),false,'new HTTP failure must not be hidden by older recent success');
now+=29_999;assert.equal(available(),false,'cooldown lasts until its exact boundary');
now+=1;assert.equal(available(),true,'cooldown ends at thirty seconds, no unbounded outage');
now+=1;scope.markProvider('airlabs',false,503);now+=1;scope.markProvider('airlabs',true,200);
assert.equal(available(),false,'in-flight success cannot shorten the fixed failure window');
now+=30_000;assert.equal(available(),true,'successful source is available after the failure window');
now+=1;scope.noteProviderError('airlabs');assert.equal(available(),false,'transport/processing exception starts cooldown too');
assert.equal(radarHealth.get('airlabs').lastHttpStatus,200,'exception must not invent a new HTTP status');
assert.equal(radarHealth.get('airlabs').lastError,now);
assert.equal(scope.providerAvailable('custom',['AIRLABS_API_KEY']),true,'other providers keep independent health');
assert.equal(scope.providerAvailable('airlabs',['MISSING_SYNTHETIC_KEY']),false,'health cannot create credential readiness');
console.log('PASS real provider cooldown: latest failure, exact expiry, recovery, exception, HTTP evidence, provider isolation and missing credential; synthetic only');
