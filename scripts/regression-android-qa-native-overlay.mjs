import assert from 'node:assert/strict';
import fs from 'node:fs';
const root='scripts/android-qa/';
const gradle=fs.readFileSync(root+'checkpoint.init.gradle','utf8');
const manifest=fs.readFileSync(root+'native/AndroidManifest.xml','utf8');
const activity=fs.readFileSync(root+'native/java/com/crewcheck/app/CheckpointQaActivity.java','utf8');
const network=fs.readFileSync(root+'native/res/xml/checkpoint_network.xml','utf8');
assert.match(gradle,/applicationIdSuffix '\.qacheckpoint'/);
assert.match(gradle,/Existing debug signer required/);
assert.doesNotMatch(gradle,/initWith|signingConfigs\.release/);
for(const tag of ['receiver','service','provider','queries']) assert.match(manifest,new RegExp('<'+tag+' tools:node="removeAll"'));
assert.match(manifest,/android:testOnly="true"/);
assert.match(manifest,/android:name="\.MainActivity" tools:node="remove"/);
assert.match(network,/<base-config cleartextTrafficPermitted="false"/);
assert.match(network,/<domain includeSubdomains="false">127\.0\.0\.1<\/domain>/);
assert.doesNotMatch(activity,/addJavascriptInterface|extends MainActivity|startActivity|crewcheck\.online|proceed\(/);
assert.match(activity,/handler\.cancel\(\)/);
assert.match(activity,/request\.deny\(\)/);
assert.match(activity,/shouldInterceptRequest/);
assert.match(activity,/setAllowFileAccess\(false\)/);
assert.match(activity,/setAllowContentAccess\(false\)/);
console.log('PASS QA overlay source checks only; no Java/Gradle compile, merged manifest, Android network enforcement or file delivery validated');
