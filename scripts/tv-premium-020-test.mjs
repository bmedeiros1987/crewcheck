import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdir, readFile } from 'node:fs/promises';
await mkdir('dist/tv-premium-020-tests',{recursive:true});
await build({entryPoints:['apps/tv-player/src/premiumContext.ts'],bundle:true,platform:'node',format:'esm',outfile:'dist/tv-premium-020-tests/context.mjs'});
const {airlineTheme,currentWeatherContexts,weatherFor}=await import('../dist/tv-premium-020-tests/context.mjs');
assert.equal(airlineTheme('LATAM Airlines Brasil'),'latam');
assert.equal(airlineTheme('GOL Linhas Aéreas'),'gol');
assert.equal(airlineTheme('Azul'),'azul');
assert.equal(airlineTheme('Outra'),'generic');
const now=Date.parse('2026-09-18T23:00:00Z');
const base={role:'base',airport:'BSB',city:'Brasília',temperature:24,label:'Céu claro',wind:10,rainChance:5,source:'crewcheck-weather/airport',observedAt:new Date(now-60000).toISOString(),expiresAt:new Date(now+600000).toISOString()};
const stay={...base,role:'stay',airport:'GRU',city:'Guarulhos',temperature:16,label:'Nublado'};
const snapshot={schemaVersion:1,weatherContexts:[base,stay]};
assert.equal(currentWeatherContexts(snapshot,now).length,2);
assert.equal(weatherFor(snapshot,'base',now)?.airport,'BSB');
assert.equal(weatherFor(snapshot,'stay',now)?.airport,'GRU');
assert.equal(currentWeatherContexts({schemaVersion:1,weatherContexts:[{...base,expiresAt:new Date(now-1).toISOString()}]},now).length,0);
const panels=await readFile('apps/tv-player/src/BroadcastPanels.tsx','utf8');
assert.match(panels,/AGORA NA SUA BASE/);
assert.match(panels,/PRÓXIMO PERNOITE/);
assert.match(panels,/airline-/);
assert.match(panels,/weatherFor\(snapshot,'base'/);
const progress=await readFile('apps/tv-player/src/SyncProgress.tsx','utf8');
assert.match(progress,/TV autorizada/);assert.match(progress,/Sincronizando sua escala/);assert.match(progress,/Preparando seu painel/);
const channel=await readFile('apps/tv-player/src/TvChannel.tsx','utf8');
assert.doesNotMatch(channel,/audio\.style\.display='none'/);
assert.match(channel,/playsinline/);
assert.match(channel,/webOSRelaunch/);
const soundtrack=await readFile('apps/tv-player/src/soundtrack.ts','utf8');
assert.match(soundtrack,/src: 'music\/crewcheck-theme\.mp3'/);
console.log('PASS: premium 0.2.0 context, day-off base weather, next-stay weather, airline visual, progress and physical-webOS audio guards.');
