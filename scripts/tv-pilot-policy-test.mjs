import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readPilotPolicy } from '../server/tv/pilot-policy.mjs';
import { createDeviceService } from '../server/tv/devices.mjs';
import { createPilotStore } from '../server/tv/pilot-store.mjs';
const sha = s => createHash('sha256').update(s).digest('hex');
const user = 'pilot@example.test', other = 'other@example.test';
const env = { CREWCHECK_TV_ENABLED: 'true', CREWCHECK_TV_PILOT_ACCOUNT_SHA256: sha(user), CREWCHECK_TV_PILOT_ORIGIN: 'https://pilot.example.test', IS_PULL_REQUEST: 'true', CREWCHECK_TV_PILOT_BOOTSTRAP: 'true' };
const p = () => readPilotPolicy(env);
assert.equal(readPilotPolicy({}).enabled, false);
assert.equal(readPilotPolicy({...env, CREWCHECK_TV_PILOT_ACCOUNT_SHA256: '*'}).enabled, false);
assert.equal(readPilotPolicy({...env, CREWCHECK_TV_PILOT_ACCOUNT_SHA256: sha(user)+','+sha(other)}).enabled, false);
for (const origin of ['http://pilot.example.test','https://u:p@pilot.example.test','https://pilot.example.test/','https://pilot.example.test/p']) assert.equal(readPilotPolicy({...env, CREWCHECK_TV_PILOT_ORIGIN: origin}).enabled, false);
assert.equal(p().allows(user), true);
assert.equal(p().allows(' PILOT@EXAMPLE.TEST '), true);
assert.equal(p().allows(other), false);
assert.equal(p().allows(''), false);
assert.equal(p().bootstrap, true);
assert.equal(readPilotPolicy({...env, IS_PULL_REQUEST:'false'}).bootstrap, false);
assert.equal(p().allowsOrigin('https://evil.example.test', true), false);
assert.equal(p().allowsOrigin('null', true), false);
assert.equal(p().allowsOrigin('null', false), true);
assert.equal(p().allowsOrigin(env.CREWCHECK_TV_PILOT_ORIGIN, true), true);
let now = 1000000, state = {};
const store = {async transaction(fn) {const draft=JSON.parse(JSON.stringify(state)); const value=await fn(draft); state=draft; return value;}};
const devices = createDeviceService({store, now:()=>now, pairingOrigin:env.CREWCHECK_TV_PILOT_ORIGIN, accountAllowed:user=>p().allows(user)});
const code = await devices.begin('lg-webos');
assert.equal(code.verificationUri, env.CREWCHECK_TV_PILOT_ORIGIN + '/tv-pair?code=' + code.userCode);
assert.equal(code.verificationUri.includes(code.deviceCode), false);
await assert.rejects(devices.approve(other,code.userCode,'private'), e=>e.status===403);
assert.equal(Object.values(state.pairings)[0].userId, undefined);
await devices.approve(user,code.userCode,'family');
await assert.rejects(devices.approve(user,code.userCode,'private'), e=>e.status===400);
const credential=await devices.poll(code.deviceCode);
assert.equal(credential.privacy,'family');
assert.equal((await devices.authorize(credential.token)).userId,user);
assert.equal(JSON.stringify(state).includes(credential.token),false);
assert.equal(JSON.stringify(state).includes(code.deviceCode),false);
await assert.rejects(devices.poll(code.deviceCode),e=>e.status===410);
await assert.rejects(devices.list(other),e=>e.status===403);
await assert.rejects(devices.revoke(other,credential.deviceId),e=>e.status===403);
env.CREWCHECK_TV_PILOT_ACCOUNT_SHA256=sha(other);
await assert.rejects(devices.authorize(credential.token),e=>e.status===403);
await assert.rejects(devices.heartbeat(credential.token),e=>e.status===403);
env.CREWCHECK_TV_PILOT_ACCOUNT_SHA256=sha(user);
await devices.revoke(user,credential.deviceId);
await assert.rejects(devices.authorize(credential.token),e=>e.status===401);
const second=await devices.begin('lg-webos'); await devices.approve(user,second.userCode);
env.CREWCHECK_TV_ENABLED='false';
await assert.rejects(devices.poll(second.deviceCode),e=>e.status===403);
env.CREWCHECK_TV_ENABLED='true'; now+=300001;
await assert.rejects(devices.poll(second.deviceCode),e=>e.status===410);
const third=await devices.begin('lg-webos'); await devices.approve(user,third.userCode); const expired=await devices.poll(third.deviceCode); now+=86400001;
await assert.rejects(devices.authorize(expired.token),e=>e.status===401);
const calls=[]; let released=false;
const mock={async query(sql,args) {calls.push(sql); if(sql.startsWith('SELECT payload')) return {rows:[{payload:{value:1}}]}; if(sql.startsWith('SELECT id')) return {rows:[{id:1}]}; return {rows:[]};},async connect(){return {...this,release(){released=true;}};}};
const dbstore=createPilotStore(async()=>mock); await dbstore.initialize(); await dbstore.check();
await assert.rejects(dbstore.transaction(draft=>{draft.value=2;throw Error('test rollback');}));
assert.equal(calls.includes('ROLLBACK'),true); assert.equal(released,true);
assert.equal(calls.some(sql=>sql.includes('crewcheck_platform_rosters')||sql.includes('crewcheck_platform_profiles')),false);
assert.equal(calls.some(sql=>sql.startsWith('UPDATE')),false);
console.log('TV pilot policy/service/store guards: PASS (single account, origins, revoke, expiry, flag changes, rollback).');
