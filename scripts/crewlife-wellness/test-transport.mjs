import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const messages = [], events = [];
const bridge = { onmessage: null, postMessage: raw => messages.push(JSON.parse(raw)) };
globalThis.window = { CrewCheckSamsung: bridge, dispatchEvent: e => events.push(e.type) };
let source = fs.readFileSync('scripts/crewlife-wellness/samsung.ts', 'utf8')
  .replace(/import \{ getStoredUser, isAuthenticated \}[^;]+;/, "const getStoredUser = () => ({id:'fixture-account'}); const isAuthenticated = () => true;");
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { samsungRequest, disconnectSamsung } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const tick = () => new Promise(resolve => setTimeout(resolve, 10));
const first = samsungRequest('status', { action:'read', owner:'plaintext', requestId:'injected' });
await tick();
assert.equal(messages[0].action, 'status');
assert.match(messages[0].owner, /^[a-f0-9]{64}$/);
assert.notEqual(messages[0].requestId, 'injected');
bridge.onmessage({data:'not json'});
bridge.onmessage({data:JSON.stringify({requestId:'unrelated',ok:true,metrics:{steps:999}})});
bridge.onmessage({data:JSON.stringify({requestId:messages[0].requestId,ok:true,available:true,keys:['steps']})});
assert.deepEqual(await first, {requestId:messages[0].requestId,ok:true,available:true,keys:['steps']});
const pending = samsungRequest('read');
const rejected = assert.rejects(pending, /Conexão encerrada/);
await tick();
disconnectSamsung();
await rejected;
assert.equal(messages.at(-1).action, 'disconnect');
assert.equal(events.at(-1), 'crewcheck:samsung-disconnected');
bridge.onmessage({data:JSON.stringify({requestId:messages[1].requestId,ok:true,metrics:{steps:999}})});
window.CrewCheckSamsung = undefined;
assert.equal((await samsungRequest('status')).available, false);
console.log('Samsung transport: account hash, request isolation, malformed/late responses and disconnect cancellation passed.');
