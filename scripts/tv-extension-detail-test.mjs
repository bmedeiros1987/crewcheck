import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {build} from 'esbuild';
import {mkdir} from 'node:fs/promises';
const main=await readFile('apps/tv-player/src/main.tsx','utf8');
const css=await readFile('apps/tv-player/src/tv.css','utf8');
const core=await readFile('packages/tv-core/src/index.ts','utf8');
assert.match(main,/selected\.activities\.map\(activity\)/);
assert.match(main,/openActivity/);
assert.match(main,/view === 'Programação'/);
assert.match(main,/Tripulação, financeiro e outros dados sensíveis só aparecerão quando o titular autorizar/);
assert.match(main,/activity-role-/);
assert.match(css,/activity-role-stay/);
assert.match(css,/program-detail-grid/);
assert.match(core,/role: "flight" \| "stay" \| "rest"/);
assert.doesNotMatch(core,/crew:/i);
assert.doesNotMatch(core,/salary:/i);
await mkdir('dist/tv-extension-tests',{recursive:true});
await build({entryPoints:['apps/tv-player/src/visitorMode.ts','apps/tv-player/src/tvPreferences.ts'],bundle:true,platform:'node',format:'esm',outdir:'dist/tv-extension-tests'});
const visitor=await import('../dist/tv-extension-tests/visitorMode.js');
assert.equal(visitor.visitorRoute('BSB'),'Brasília (BSB)');
assert.equal(visitor.visitorCode('HSB'),'Sobreaviso em casa');
const prefs=await import('../dist/tv-extension-tests/tvPreferences.js');
const mem={getItem:()=>null,setItem:()=>{}};
assert.equal(prefs.readTvDisplay(mem).showCrew,false);
assert.equal(prefs.readTvDisplay(mem).showFinance,false);
console.log('PASS: TV extension exposes full day drilldown, distinct stay cards, visitor translation and fail-closed sensitive preferences.');
