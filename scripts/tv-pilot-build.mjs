import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
const value = process.env.TV_PILOT_API_ORIGIN;
if (!value) throw Error('TV_PILOT_API_ORIGIN required');
const url = new URL(value);
if (url.protocol !== 'https:' || url.origin !== value || url.username || url.password) throw Error('Exact HTTPS pilot origin required');
const child = spawnSync(process.execPath, ['scripts/tv-build.mjs', 'lg-webos'], { stdio:'inherit', env:{...process.env, VITE_TV_DEMO:'false', VITE_CREWCHECK_TV_ENABLED:'true', VITE_TV_API_ORIGIN:value} });
if (child.status !== 0) throw Error('Pilot build failed');
const folder = 'dist/lg-webos';
const manifest = JSON.parse(await readFile(folder+'/appinfo.json','utf8'));
manifest.id = 'online.crewcheck.tv.pilot';
manifest.title = 'CrewCheck TV Piloto';
manifest.version = '0.1.5';
await writeFile(folder+'/appinfo.json', JSON.stringify(manifest,null,2)+'\n');
const metadata = JSON.parse(await readFile(folder+'/tv-build.json','utf8'));
if (metadata.demo !== false || metadata.apiOrigin !== value) throw Error('Pilot must not contain demo configuration');
metadata.operational = false;
metadata.realAccountPilot = true;
metadata.version = manifest.version;
metadata.note = 'Restricted real-account test with optional per-TV screen care; not store-approved. The user must authorize the device. No account token or password bundled.';
await writeFile(folder+'/tv-build.json', JSON.stringify(metadata,null,2)+'\n');
console.log('Staged restricted LG pilot; no signing, installation, account authorization or store submission claimed.');
