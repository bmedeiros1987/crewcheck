import assert from 'node:assert/strict';
import { wellhubOpeningStatus as status, prioritizeWellhubOpening } from '../shared/wellhub-hours.mjs';
const unit={name:'SYNTHETIC UNIT',verifiedAt:'2033-01-03',timeZone:'America/Sao_Paulo',openingHours:['seg-sex 06:00-23:00']};
const at=(time,partner=unit)=>status(partner,new Date(time));
assert.equal(at('2033-01-04T01:29:59Z').status,'open');
assert.equal(at('2033-01-04T01:30:00Z').status,'closing-soon');
assert.match(at('2033-01-04T01:59:00Z').label,/🟡 Fecha em breve · em 1 min pelo horário cadastrado/);
assert.equal(at('2033-01-04T02:00:00Z').status,'closed');
const overnight={...unit,openingHours:['seg 22:00-01:00','ter 08:00-18:00']};
assert.equal(at('2033-01-04T02:59:00Z',overnight).status,'open');
assert.equal(at('2033-01-04T03:59:00Z',overnight).status,'closing-soon');
assert.equal(at('2033-01-04T04:00:00Z',overnight).status,'closed');
const joined={...unit,openingHours:['seg 22:00-00:00','ter 00:00-02:00']};
assert.equal(at('2033-01-04T02:59:00Z',joined).status,'open','midnight split is not a closure');
assert.equal(at('2033-01-04T04:59:00Z',joined).status,'closing-soon');
assert.equal(at('2033-01-04T02:59:00Z',{...unit,openingHours:['seg 22:00-01:00','seg 23:00-02:00']}).status,'open');
const pause={...unit,openingHours:['seg 06:00-12:00, 14:00-23:00']};
assert.equal(at('2033-01-03T14:59:00Z',pause).status,'closing-soon');
assert.equal(at('2033-01-03T15:00:00Z',pause).status,'closed');
for(const patch of [{openingHours:[]},{timeZone:'bad/zone'},{verifiedAt:'2030-01-01'},{holidayHoursUncertain:true}])assert.equal(at('2033-01-04T01:59:00Z',{...unit,...patch}).status,'unknown');
assert.equal(at('2033-01-04T01:59:00Z',{...unit,timeZone:'America/Manaus'}).status,'open','unit zone, not device zone');
assert.equal(at('2033-01-04T02:59:00Z',{...unit,is24Hours:true,openingHours:['seg-dom 00:00-23:59']}).status,'open');
const sorted=prioritizeWellhubOpening([{...unit,id:'closed',openingHours:['seg 06:00-20:00']},{...unit,id:'soon'},{...unit,id:'unknown',openingHours:[]}],new Date('2033-01-04T01:59:00Z'));
assert.deepEqual(sorted.map(p=>p.id),['soon','unknown','closed']);
console.log('PASS synthetic closing-soon: 30-minute/exact-close, local zone, overnight, contiguous/overlap, pause, missing/stale/holiday, 24h and stable ranking',process.env.TZ);
