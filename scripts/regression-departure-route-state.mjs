import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const code = ts.transpileModule(fs.readFileSync('client/src/lib/departureRouteState.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.ES2022 } }).outputText;
const { createDepartureRouteSession } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const states = [];
let now = '2026-10-02T02:59:00Z';
const session = createDepartureRouteSession(value => states.push(value), () => now);
const old = session.begin();
assert.equal(states.at(-1).clientRouteState, 'pending');
assert.equal(states.at(-1).distanceMeters, undefined, 'missing GPS/route cannot imply long distance');
const newer = session.begin();
session.complete(newer, {ok:true, distanceMeters:500000, provider:'offline', durationSeconds:18000});
assert.equal(states.at(-1).clientRouteState, 'valid');
session.complete(old, {ok:true, distanceMeters:1000});
assert.equal(states.at(-1).distanceMeters, 500000, 'older request cannot replace latest route');
now = '2026-10-02T03:01:00Z'; // midnight crossed in Sao Paulo; canonical observation unchanged
const refresh = session.begin();
assert.equal(states.at(-1).clientRouteState, 'stale');
assert.equal(states.at(-1).distanceMeters, 500000);
session.complete(refresh, {ok:false, message:'Offline fixture'});
assert.equal(states.at(-1).clientRouteState, 'stale');
assert.equal(states.at(-1).clientRouteError, 'Offline fixture');
assert.equal(states.at(-1).updatedAt, '2026-10-02T02:59:00Z');
assert.equal(states.at(-1).provider, 'offline');
const late = session.begin();
session.dispose();
const count = states.length;
session.complete(late, {ok:true,distanceMeters:800000});
assert.equal(states.length, count, 'disposed event/account/origin cannot publish');
const fresh = createDepartureRouteSession(value => states.push(value), () => now);
const missing = fresh.begin();
assert.equal(states.at(-1).distanceMeters, undefined, 'new identity does not inherit last route');
fresh.complete(missing, {ok:false, message:'GPS unavailable'});
assert.equal(states.at(-1).clientRouteState, 'error');
assert.equal(states.at(-1).distanceMeters, undefined);
const recover = fresh.begin();
fresh.complete(recover, {ok:true,distanceMeters:12000});
assert.equal(states.at(-1).clientRouteState, 'valid');
assert.equal(states.at(-1).clientRouteError, '');
console.log('PASS pending/valid/stale/error, same-route retention, reverse responses, identity disposal, missing origin, midnight canonical timestamp');

const preparedHome = fs.readFileSync('client/src/pages/Home.tsx', 'utf8');
const card = preparedHome.slice(preparedHome.indexOf('function SmartCard('), preparedHome.indexOf('function UpdateCenterView('));
assert.ok(card.includes("isPositioningSearchPending(readPositioningSearch(event)) ? 'Confirmar posicionamento' : 'Dia anterior'"), 'Home card must distinguish pending search from terminal positioning fallback');
